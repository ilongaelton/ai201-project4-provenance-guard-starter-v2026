def validate() -> list[str]:
    """Complain about anything malformed, before a long run rather than during."""
    problems = []
    for i, scenario in enumerate(SCENARIOS, 1):
        if not scenario.get("name"):
            problems.append(f"scenario {i} has no name")

        kinds = [k for k in ("texts", "bodies", "appeals") if scenario.get(k)]
        if len(kinds) != 1:
            problems.append(f"scenario {i} ('{scenario.get('name')}') needs exactly one of "
                            f"texts / bodies / appeals, has {kinds or 'none'}")
            continue

        if kinds == ["bodies"]:
            continue  # sent as written; non-objects are deliberate (criterion 5)

        texts = scenario["texts"] if kinds == ["texts"] else scenario["appeals"].get("texts", [])
        for j, text in enumerate(texts, 1):
            if not str(text).strip():
                problems.append(f"scenario {i}, text {j} is empty — use 'bodies' for that")
            elif str(text).startswith("REPLACE ME"):
                problems.append(f"scenario {i} ('{scenario.get('name')}'), text {j} is still "
                                f"the placeholder")
    return problems
